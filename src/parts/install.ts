import { createHash, pbkdf2Sync, randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { FACTORY_ROOT } from "../config.js";
import { APP_ENTRY, MIGRATIONS_DIR, readProductRecord, writeProductRecord } from "../deploy/app.js";
import type { ClientPaths } from "../lib/paths.js";
import type { FactoryPart, ProductModule } from "../products/registry.js";

/**
 * Ready-made parts of app sites (Web Stüdyosu, step 3): tested factory code in parts/, copied into a client by this
 * installer, never written by the agent. The agent only places the site-side markup (rules/parts.md).
 *
 *   parts/app/core.js         router, admin sign-in, rate limits      → app/parts/core.js     (every app site)
 *   parts/app/admin.html      the client's admin screen               → app/admin.html        (every app site)
 *   parts/app/<part>.js       one module per part                     → app/parts/<part>.js
 *   parts/migrations/NNNN_*   tables; numbers are global and fixed    → app/migrations/        (added, never changed)
 *   parts/site/arke-parts.js    site side: catalogue and forms          → site/js/arke-parts.js
 *
 * app/worker.js is generated from the parts the kind uses, so a kind ships only its own code.
 */
export const PARTS_DIR = path.join(FACTORY_ROOT, "parts");
export const SITE_PARTS_JS = "js/arke-parts.js";
/** Written into the client by the panel, so the deploy tool knows which secrets the installed parts need. */
export const ADMIN_PASSWORD_SECRET = "ADMIN_PASSWORD_HASH";
export const SESSION_SECRET = "SESSION_SECRET";
export const NOTIFY_WEBHOOK_SECRET = "NOTIFY_WEBHOOK_URL";
const PBKDF2_ITERATIONS = 100_000; // the most Cloudflare Workers' WebCrypto allows
export const MIN_ADMIN_PASSWORD = 10;

interface PartSpec {
  /** The part's Worker module (parts/app/<file>), imported by the generated worker.js. */
  readonly module?: { readonly file: string; readonly name: string };
  readonly migrations: readonly string[];
  readonly site: boolean;
  readonly secrets: readonly string[];
  readonly optionalSecrets: readonly string[];
}

const CORE: PartSpec = {
  migrations: ["0001_core.sql", "0004_privacy.sql"],
  site: false,
  secrets: [ADMIN_PASSWORD_SECRET, SESSION_SECRET],
  optionalSecrets: [],
};

/** Parts that are ready today; the others (cart, payments, calendar, menu-qr, legal-pages) come in later steps. */
export const READY_PARTS: Partial<Record<FactoryPart, PartSpec>> = {
  admin: CORE,
  catalog: { module: { file: "catalog.js", name: "catalog" }, migrations: ["0002_catalog.sql"], site: true, secrets: [], optionalSecrets: [] },
  notifications: {
    module: { file: "inbox.js", name: "notifications" },
    migrations: ["0003_inbox.sql"],
    site: true,
    secrets: [],
    optionalSecrets: [NOTIFY_WEBHOOK_SECRET],
  },
};

export interface InstallResult {
  readonly installed: boolean;
  readonly parts: readonly FactoryPart[];
  /** Files written or replaced (relative to the client folder). */
  readonly written: readonly string[];
  /** Factory migrations whose copy in the client differs (left alone: an applied migration is never changed). */
  readonly migrationConflicts: readonly string[];
}

function writeIfChanged(file: string, content: string, written: string[], rel: string): void {
  if (existsSync(file) && readFileSync(file, "utf8") === content) return;
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, content);
  written.push(rel);
}

export function workerSource(specs: readonly PartSpec[]): string {
  const mods = specs.flatMap((s) => (s.module ? [s.module] : []));
  return [
    "// Generated by Arke Web Studio from the parts this site uses. Factory-owned: do not edit (it is rewritten).",
    'import adminHtml from "./admin.html";',
    'import { createApp } from "./parts/core.js";',
    ...mods.map((m) => `import ${m.name} from "./parts/${m.file}";`),
    "",
    `export default createApp({ adminHtml, parts: [${mods.map((m) => m.name).join(", ")}] });`,
    "",
  ].join("\n");
}

/**
 * Copies the ready parts a kind uses into the client (idempotent; only changed files are written) and records the
 * secrets they need. Static kinds get nothing. Runs in the panel and before an app publish, never for the agent.
 */
export function installParts(paths: ClientPaths, module: ProductModule): InstallResult {
  if (module.deploy !== "app") return { installed: false, parts: [], written: [], migrationConflicts: [] };
  const parts = module.parts.filter((p) => READY_PARTS[p]);
  const specs = [CORE, ...parts.map((p) => READY_PARTS[p]!).filter((s) => s !== CORE)];
  const written: string[] = [];
  const conflicts: string[] = [];
  const src = (...p: string[]) => readFileSync(path.join(PARTS_DIR, ...p), "utf8");

  writeIfChanged(path.join(paths.root, "app", "parts", "core.js"), src("app", "core.js"), written, "app/parts/core.js");
  writeIfChanged(path.join(paths.root, "app", "admin.html"), src("app", "admin.html"), written, "app/admin.html");
  for (const s of specs) {
    if (s.module) writeIfChanged(path.join(paths.root, "app", "parts", s.module.file), src("app", s.module.file), written, `app/parts/${s.module.file}`);
    for (const m of s.migrations) {
      const dest = path.join(paths.root, MIGRATIONS_DIR, m);
      const want = src("migrations", m);
      if (!existsSync(dest)) writeIfChanged(dest, want, written, `${MIGRATIONS_DIR}/${m}`);
      else if (readFileSync(dest, "utf8") !== want) conflicts.push(m);
    }
  }
  writeIfChanged(path.join(paths.root, APP_ENTRY), workerSource(specs), written, APP_ENTRY);
  if (specs.some((s) => s.site)) writeIfChanged(path.join(paths.root, "site", SITE_PARTS_JS), src("site", "arke-parts.js"), written, `site/${SITE_PARTS_JS}`);

  const record = readProductRecord(paths);
  const secrets = [...new Set(specs.flatMap((s) => s.secrets))].sort();
  const optionalSecrets = [...new Set(specs.flatMap((s) => s.optionalSecrets))].sort();
  if (JSON.stringify(record.secrets ?? []) !== JSON.stringify(secrets) || JSON.stringify(record.optionalSecrets ?? []) !== JSON.stringify(optionalSecrets))
    writeProductRecord(paths, { ...record, product: module.id, secrets, optionalSecrets });
  return { installed: true, parts: ["admin", ...parts.filter((p) => p !== "admin")], written, migrationConflicts: conflicts };
}

/** True when `text` is exactly the factory's site script: only then may it make requests (to this site's own API). */
export function isFactorySiteScript(rel: string, text: string): boolean {
  if (rel !== SITE_PARTS_JS) return false;
  const file = path.join(PARTS_DIR, "site", "arke-parts.js");
  return existsSync(file) && sha(readFileSync(file, "utf8")) === sha(text);
}

const sha = (s: string) => createHash("sha256").update(s).digest("hex");

/** The admin password as the Worker checks it (core.js verifyPassword). The password itself is never kept. */
export function hashAdminPassword(password: string): string {
  if (password.length < MIN_ADMIN_PASSWORD) throw new Error(`Parola en az ${MIN_ADMIN_PASSWORD} karakter olmalı.`);
  if (password.length > 200) throw new Error("Parola en fazla 200 karakter olabilir.");
  const salt = randomBytes(16);
  const hash = pbkdf2Sync(password, salt, PBKDF2_ITERATIONS, 32, "sha256");
  return `pbkdf2-sha256$${PBKDF2_ITERATIONS}$${salt.toString("base64")}$${hash.toString("base64")}`;
}

/** A fresh random key for signing the admin screen's sign-in cookie. */
export const newSessionSecret = (): string => randomBytes(48).toString("base64url");
